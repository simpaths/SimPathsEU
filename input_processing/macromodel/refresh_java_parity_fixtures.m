function info = refresh_java_parity_fixtures(country, simpaths_repo)
% REFRESH_JAVA_PARITY_FIXTURES  Regenerate the MATLAB-Java parity fixtures.
%
%   info = REFRESH_JAVA_PARITY_FIXTURES(country) copies the current export bundle
%   into SimPathsEU's test resources as a coherent, stamped snapshot.
%   REFRESH_JAVA_PARITY_FIXTURES(country, simpaths_repo) overrides the repo path;
%   the default is the repository root, two levels up from input_processing/macromodel/.
%
% WHY THIS EXISTS. The parity fixture pins two different things at once: that
% MATLAB and Java AGREE (must never break), and that the numbers are SPECIFIC
% VALUES (must change whenever a bug is fixed or a parameter recalibrated).
% Freezing the file conflates them, so every legitimate fix turned into a "the
% rules forbid me from fixing this bug" argument, and the fixture instead went
% stale: on 2026-08-18 it was found to predate both the current TFP calibration
% (g_A_terminal 0.8% vs the live 0.5%) and MATLAB gaining the SimPaths-consistent
% demographic override in the handoff solve. The parity test passed the whole
% time, against a MATLAB that no longer existed.
%
% The safety property is NOT the numbers. It is that Java reproduces whatever
% MATLAB currently produces, over the path production actually uses. So:
%
%   1. Change both sides.
%   2. Run this.
%   3. Re-run RamseyTrendModelTest. It MUST pass at RELATIVE_TOLERANCE = 1e-9.
%   4. Commit the fixture diff together with the code change that caused it.
%
% Step 3 is the gate. Parity passing after regeneration proves the two sides
% agree on the NEW rule; that is strictly stronger than pinning old numbers.
% Never hand-edit a fixture, and never regenerate one to make a red test green
% without understanding why it went red.

    arguments
        country (1,:) char
        simpaths_repo (1,:) char = fullfile('..', '..')
    end

    export_dir = artifact_path('bundle', '', 'country', country);
    fixture_dir = fullfile(simpaths_repo, 'src', 'test', 'resources', 'macro', 'exogenous');

    if ~exist(export_dir, 'dir')
        error('wellsim:parityFixtures:noExport', ...
              ['No export bundle at %s. Run export_ramsey_for_simpaths(''%s'') ' ...
               '(or the full workflow) first.'], export_dir, country);
    end
    if ~exist(fixture_dir, 'dir')
        error('wellsim:parityFixtures:noFixtureDir', ...
              'Fixture directory %s not found; check simpaths_repo.', fixture_dir);
    end

    % A fixture is only meaningful as a COHERENT SET: params, reference, terminal
    % state and both projections must come from one MATLAB run. Mixing sources is
    % what produced the 6.3% consumption mismatch on 2026-08-18.
    files = { ...
        sprintf('growth_params_%s.json', country),          sprintf('growth_params_%s.json', country); ...
        % Destination keeps lower(country): the Java loader derives this name by
        % lower-casing the tag it reads from growth_params_<Country>.json, so a
        % capitalised copy resolves on Windows and fails on Linux CI.
        sprintf('growth_model_reference_%s.csv', lower(country)), sprintf('growth_model_reference_%s.csv', lower(country)); ...
        'growth_terminal_state.json',                       'growth_terminal_state.json'; ...
        sprintf('population_projection_%s.csv', country),   sprintf('population_projection_%s.csv', country); ...
        sprintf('hours_projection_%s.csv', country),        sprintf('hours_projection_%s.csv', country)};

    for i = 1:size(files, 1)
        src = fullfile(export_dir, files{i, 1});
        if ~exist(src, 'file')
            error('wellsim:parityFixtures:incomplete', ...
                  ['%s is missing from the export bundle. The fixture must be a ' ...
                   'coherent set from one run; refusing to copy a partial one.'], files{i, 1});
        end
        copyfile(src, fullfile(fixture_dir, files{i, 2}));
    end

    % Provenance, so a stale fixture is visible rather than inferred.
    stamp = fullfile(fixture_dir, 'FIXTURE_PROVENANCE.txt');
    fid = fopen(stamp, 'w');
    if fid < 0
        error('wellsim:parityFixtures:cannotStamp', 'Cannot write %s.', stamp);
    end
    closer = onCleanup(@() fclose(fid));
    fprintf(fid, 'MATLAB-Java parity fixture, exogenous mode\n');
    fprintf(fid, 'Generated by refresh_java_parity_fixtures(''%s'')\n', country);
    fprintf(fid, 'Date          : %s\n', datestr(now, 'yyyy-mm-dd HH:MM:SS')); %#ok<TNOW1,DATST>
    fprintf(fid, 'Source bundle : %s\n', repo_relative_path(export_dir));

    gp = fullfile(export_dir, sprintf('growth_params_%s.json', country));
    txt = fileread(gp);
    for key = {'g_A_terminal_annual', 'rho_quarterly', 'terminal_tail_quarters', 'alpha_K', 'sigma'}
        tok = regexp(txt, ['"' key{1} '"\s*:\s*([-0-9.eE]+)'], 'tokens', 'once');
        if ~isempty(tok)
            fprintf(fid, '%-14s: %s\n', key{1}, tok{1});
        end
    end
    fprintf(fid, '\nRegenerate with refresh_java_parity_fixtures, never by hand, and re-run\n');
    fprintf(fid, 'RamseyTrendModelTest afterwards: it must pass at 1e-9. Commit this file\n');
    fprintf(fid, 'with the fixture and with the code change that made the numbers move.\n');
    clear closer;

    info = struct('fixture_dir', fixture_dir, 'files', {files(:, 2)'}, 'stamp', stamp);

    fprintf('  ✓ parity fixtures refreshed in %s\n', fixture_dir);
    fprintf('    NEXT: run RamseyTrendModelTest in SimPathsEU. It must pass at 1e-9.\n');
end


function root_rel = repo_relative_path(rel)
% Mirror of repo_relative in internal/write_bundle_provenance.m: the bundle path
% is recorded relative to the SimPathsEU root with forward slashes, so the tracked
% FIXTURE_PROVENANCE.txt does not change with the platform of whoever refreshes it
% (JuergenWiemers/SimPathsEU#14). pwd is the model root, model_location().repo_rel;
% each leading '../' drops one of its segments. Absolute paths are left alone.
    rel = strrep(rel, '\', '/');
    if ~isempty(regexp(rel, '^([A-Za-z]:)?/', 'once'))
        root_rel = rel;
        return;
    end
    base = strsplit(model_location().repo_rel, '/');
    while startsWith(rel, '../')
        if ~isempty(base)
            base(end) = [];
        end
        rel = rel(4:end);
    end
    root_rel = strjoin([base, {rel}], '/');
end
